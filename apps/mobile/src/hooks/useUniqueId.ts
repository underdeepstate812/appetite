import { useState } from "react";

let counter = 0;

/**
 * Уникальный на всё приложение идентификатор для SVG-определений (градиенты, клипы).
 * Фиксированный id вроде "levelRing" ломается, когда два экземпляра компонента живут в документе одновременно
 * (в стеке навигации нижний экран остаётся смонтированным): браузер берёт ПЕРВОЕ определение с таким id —
 * оно лежит в скрытом экране и не разрешается, и заливка пропадает (логотип превращался в точку).
 */
export function useUniqueId(prefix: string): string {
  const [id] = useState(() => `${prefix}-${++counter}`);
  return id;
}
